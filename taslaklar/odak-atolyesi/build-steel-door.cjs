// Prototype-only source conversion. Keep every supplied triangle; centimetres, no scaling.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../..'),source='referanslar/2026-10-26-celik-kapi/250cm-280cm-300cm-celik-kapi.stl';
const bytes=fs.readFileSync(path.join(root,source)),sha256=crypto.createHash('sha256').update(bytes).digest('hex');
assert.equal(sha256,'fd5cdbcbb14800b0950c5c443e5b00c715d8bd2c73ea5c8106752b693ac8472b','Steel-door source changed; inspect it before rebuilding');
const count=bytes.readUInt32LE(80);assert.equal(bytes.length,84+count*50);
const groups=[250,280,300].map(height=>({height,triangles:[]}));
for(let i=0;i<count;i++){
 const v=Array.from({length:9},(_,j)=>bytes.readFloatLE(84+i*50+12+j*4));assert.ok(v.every(Number.isFinite));
 const group=Math.round(((v[0]+v[3]+v[6])/3-62.5)/250);assert.ok(groups[group]);
 for(let j=0;j<9;j+=3)v[j]-=group*250;groups[group].triangles.push(v);
}
const models=groups.map(({height,triangles})=>{
 assert.equal(triangles.length,9445);
 // Weld for component/material classification only. The exported coordinates stay exact.
 const parent=triangles.map((_,i)=>i),at=new Map();
 function find(i){while(parent[i]!==i){parent[i]=parent[parent[i]];i=parent[i];}return i;}
 triangles.forEach((v,i)=>{for(let j=0;j<9;j+=3){const key=v.slice(j,j+3).map(n=>Math.round(n*1e5)).join(',');if(at.has(key))parent[find(i)]=find(at.get(key));else at.set(key,i);}});
 const components=new Map();triangles.forEach((v,i)=>{const key=find(i);if(!components.has(key))components.set(key,[]);components.get(key).push(i);});assert.equal(components.size,15);
 const materials=['panel','steelFrame','steelLeaf','steelInset','hardware'],materialIds=Buffer.alloc(triangles.length),parts=[];
 for(const ids of components.values()){
  const lo=[Infinity,Infinity,Infinity],hi=[-Infinity,-Infinity,-Infinity];
  for(const i of ids)for(let j=0;j<9;j++){const k=j%3;lo[k]=Math.min(lo[k],triangles[i][j]);hi[k]=Math.max(hi[k],triangles[i][j]);}
  const dx=hi[0]-lo[0],dz=hi[2]-lo[2];
  const material=dx>124&&dz>249?'panel':dx>90&&Math.abs(dz-205)<.01?'steelFrame':dx>75&&dz>196?'steelLeaf':dx>44&&dz>161?'steelInset':'hardware';
  ids.forEach(i=>materialIds[i]=materials.indexOf(material));parts.push({material,triangles:ids.length,min:lo,max:hi});
 }
 for(const m of materials)assert.ok(parts.some(p=>p.material===m));
 const panel=parts.find(p=>p.material==='panel');assert.equal(panel.triangles,90);assert.equal(panel.max[2],height);
 const packed=Buffer.alloc(triangles.length*36);triangles.forEach((v,i)=>v.forEach((n,j)=>packed.writeFloatLE(n,i*36+j*4)));
 return {key:'steel-'+height,source,sha256,height,width:125,centerX:62.5,wallCenterY:(panel.min[1]+panel.max[1])/2,
  frontSide:-1,hingeSide:1,nominalWidth:90,nominalHeight:205,frameWidth:parts.find(p=>p.material==='steelFrame').max[0]-parts.find(p=>p.material==='steelFrame').min[0],
  materials,parts,triangleCount:triangles.length,positionsBase64:packed.toString('base64'),materialIdsBase64:materialIds.toString('base64')};
});
const loader=`
for(const m of window.SteelDoorSTLModels){
 const raw=Uint8Array.from(atob(m.positionsBase64),c=>c.charCodeAt(0)),view=new DataView(raw.buffer);
 m.vertices=Float32Array.from({length:raw.length/4},(_,i)=>view.getFloat32(i*4,true));
 m.materialIds=Uint8Array.from(atob(m.materialIdsBase64),c=>c.charCodeAt(0));
 delete m.positionsBase64;delete m.materialIdsBase64;
}
`;
fs.writeFileSync(path.join(__dirname,'steel-door-models.js'),'/* Generated by build-steel-door.cjs from the supplied STL; exact float coordinates. */\nwindow.SteelDoorSTLModels='+JSON.stringify(models)+';\n'+loader);
console.log('Steel door: 3 exact panels (125 x 250 / 280 / 300 cm), 9445 triangles each; source SHA verified.');
